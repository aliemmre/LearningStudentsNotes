    private void writeResults() {
        List<MyLinkedList> list = fileEngine.writeResultsOnTextArea(
                sourceList, targetList, lessonName, sourceListName);
        StringBuilder text = new StringBuilder(lessonName + " sonuçları\n\n");
        for (MyLinkedList student : list) {
            if (student.isEmpty()) continue;
            for (int i = 1; i < student.size2(); i++) {
                if (student.getStr1(i).equals(lessonName)) {
                    text.append(student.getStr1(0)).append(" -> ")
                            .append(student.getStr2(0)).append(" -> ")
                            .append(student.getStr2(i)).append('\n');
                }
            }
        }
        ResultsjTextArea.setText(text.toString());
    }

