    private void jButtonMakeTxtActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonMakeTxtActionPerformed
        String value = jTextFieldLessonOrName.getText().trim();
        boolean created;
        if (jRadioButtonLesson.isSelected()) {
            created = fileEngine.makeTxtLesson(value);
        } else if (jRadioButtonStudentInformation.isSelected()) {
            created = fileEngine.makeTxtStudentNotes(value);
        } else if (jRadioButtonAllOfThem.isSelected()) {
            created = fileEngine.makeTxtAllResults(sourceListName);
        } else {
            JOptionPane.showMessageDialog(this, "Bir çıktı türü seçin.");
            return;
        }
        JOptionPane.showMessageDialog(this, created
                ? "TXT masaüstünde oluşturuldu."
                : "TXT oluşturulamadı. Girdiğiniz ders/numarayı ve dosya yazma iznini kontrol edin.");
    }//GEN-LAST:event_jButtonMakeTxtActionPerformed

